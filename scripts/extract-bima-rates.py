"""Extract Plan 770 base annual rates from the supplied 408-page rate book.

Usage: python scripts/extract-bima-rates.py <rate-book.pdf>
Requires PyMuPDF. Only the base-rate tables on PDF pages 127-135 are read;
Class I extras and rider tables are deliberately excluded.
"""
import json
import re
import sys
from pathlib import Path
import pymupdf

pdf = pymupdf.open(sys.argv[1])
assert len(pdf) == 408, 'Expected the supplied 408-page Plan 770 rate book'
rates = {str(p): {} for p in [7, 10, 12, 15, 18]}
ppt, terms = 7, None
for page_number in range(127, 136):
    headings = []
    stop_y = float('inf')
    for block in pdf[page_number - 1].get_text('blocks'):
        match = re.search(r'Premium paying term\s*=\s*(7|10|12|15|18)\s*years', block[4])
        if match:
            headings.append((block[1], int(match[1])))
        if 'Class I extra' in block[4]:
            stop_y = block[1]
    headings.sort()
    words = sorted(pdf[page_number - 1].get_text('words'), key=lambda w: (round(w[1], 1), w[0]))
    lines = []
    for word in words:
        if not lines or abs(lines[-1][0][1] - word[1]) > 2.5:
            lines.append([word])
        else:
            lines[-1].append(word)
    for line in lines:
        if line[0][1] >= stop_y:
            break
        while headings and headings[0][0] <= line[0][1] + 1:
            _, ppt = headings.pop(0)
            terms = None
        cells = [w[4] for w in sorted(line, key=lambda w: w[0])]
        text = ' '.join(cells)
        if 'Class I extra' in text:
            break
        if cells[0] == 'Age' and all(c.isdigit() for c in cells[1:]):
            terms = list(map(int, cells[1:]))
            continue
        if terms and len(cells) == len(terms) + 1 and cells[0].isdigit():
            age = cells[0]
            assert 0 <= int(age) <= 55
            for term, value in zip(terms, cells[1:]):
                if value == '-':
                    continue
                assert re.fullmatch(r'\d+\.\d{2}', value), (page_number, cells)
                key = str(term)
                row = rates[str(ppt)].setdefault(age, {})
                assert key not in row, ('Duplicate', ppt, age, term)
                row[key] = float(value)

limits = {7: (11, 55), 10: (8, 55), 12: (6, 53), 15: (3, 50), 18: (0, 47)}
for ppt, (minimum, maximum) in limits.items():
    for age in range(minimum, maximum + 1):
        for term in range(max(ppt + 10, 28 - age), min(40, 75 - age) + 1):
            assert str(term) in rates[str(ppt)].get(str(age), {}), ('Missing', ppt, age, term)
    actual = sum(len(row) for row in rates[str(ppt)].values())
    expected = sum(max(0, min(40, 75-age) - max(ppt+10, 28-age) + 1) for age in range(minimum, maximum+1))
    assert actual == expected, (ppt, actual, expected)

target = Path(__file__).resolve().parents[1] / 'lic/bima-platinum/premium-rates.js'
target.write_text('// Plan 770 base annual premium per Rs.1,000 BSA. Supplied rate book, PDF pp.127-135.\n'
                  '// Generated by scripts/extract-bima-rates.py; no interpolation or rider rates.\n'
                  'globalThis.BIMA_PREMIUM_RATES = ' + json.dumps(rates, separators=(',', ':')) + ';\n', encoding='utf-8')
print('Extracted', sum(len(row) for group in rates.values() for row in group.values()), 'base premium rates')


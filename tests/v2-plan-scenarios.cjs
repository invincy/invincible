const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async function exercisePlanEditor({browser, base, output, name}) {
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('https://**/*', route => route.abort());
  const plan = 'Project: LMV imported\nDescription: Complete and validate the model.\n\n1. Research\n   Notes: Keep the dimensions.\n   - [ ] Gather references\n   - [x] Verify measurements\n\n2. Build the model\n   - [ ] Create the base';
  const paste = () => page.locator('.v2-workspace-actions').getByRole('button',{name:'Paste plan',exact:true}).click();
  const open = id => page.locator(`[data-task-id="${id}"] .v2-task-card`).click();
  try {
    await page.goto(base+'/fixture#workspace');
    await paste();
    await page.getByLabel('Plan text',{exact:true}).fill(plan);
    await page.getByRole('button',{name:'Preview plan',exact:true}).click();
    await page.getByRole('region',{name:'Plan preview'}).waitFor();
    assert.equal(await page.getByLabel('Substep 1.2 title',{exact:true}).inputValue(),'Verify measurements');
    await page.getByLabel('Step 2 title',{exact:true}).fill('Build refined model');
    assert.equal(await page.evaluate(()=>window.writes),0,'pasting, previewing and editing the preview never writes');
    await page.screenshot({path:path.join(output,name+'-plan-preview.png')});
    await page.evaluate(()=>window.failNextWrite=true);
    await page.getByRole('button',{name:'Create project',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Saving was denied'}).waitFor();
    assert.equal(await page.evaluate(()=>window.writes),0);
    await page.reload();
    await paste();
    assert.equal(await page.getByLabel('Plan text',{exact:true}).inputValue(),plan);
    assert.equal(await page.getByLabel('Step 2 title',{exact:true}).inputValue(),'Build refined model','edited preview survives failed save and reload');
    await page.evaluate(()=>window.loseNextAck=true);
    await page.getByRole('button',{name:'Create project',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'could not be confirmed'}).waitFor();
    assert.equal(await page.evaluate(()=>window.taskRecords().filter(task=>task.title==='LMV imported').length),1);
    await page.getByRole('button',{name:'Create project',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'detached'});
    assert.equal(await page.evaluate(()=>window.taskRecords().filter(task=>task.title==='LMV imported').length),1,'retry after an unconfirmed create uses the same project ID');
    const id=await page.evaluate(()=>window.taskRecords().find(task=>task.title==='LMV imported').id);
    let record=await page.evaluate(id=>window.taskRecords().find(task=>task.id===id),id);
    assert.equal(record.steps.length,2); assert.equal(record.stepSubsteps[record.steps[0].id].length,2);
    assert.equal(record.steps[0].notes,'Keep the dimensions.');
    assert.equal(record.subtasks.length,2,'legacy mirror contains parent steps, not a flattened child list');
    await page.reload();
    await open(id);
    await page.locator('.v2-task-route-select').filter({hasText:'Build refined model'}).click();
    assert.equal(await page.getByLabel('Step 2 title',{exact:true}).inputValue(),'Build refined model');
    await page.locator('.v2-task-route-select').filter({hasText:'Research'}).click();
    await page.getByLabel('Step 1 notes',{exact:true}).fill('Updated working notes\nwith another line.');
    await page.getByLabel('Complete substep 1.1',{exact:true}).check();
    assert.equal(await page.getByLabel('Complete step 1',{exact:true}).isChecked(),true);
    await page.getByRole('button',{name:'Save project',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.v2-task-save-actions .v2-primary')?.disabled);
    await page.getByRole('button',{name:/Close saved work/}).click();
    await page.getByRole('region',{name:/Task workspace/}).waitFor({state:'detached'});
    record=await page.evaluate(id=>window.taskRecords().find(task=>task.id===id),id);
    assert.equal(record.steps[0].done,true); assert.equal(record.subtasks[0].done,true);
    assert.equal(record.steps[0].notes,'Updated working notes\nwith another line.');

    // Editing uses content conflict checks, but unrelated lane changes are preserved.
    await open('t0');
    await page.getByLabel('Project description',{exact:true}).fill('My unsaved local description');
    await page.evaluate(()=>window.remoteEditTask('t0',{title:'Changed on another device'}));
    await page.getByRole('button',{name:'Save project',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'changed elsewhere'}).waitFor();
    assert.equal(await page.evaluate(()=>window.taskRecords()[0].title),'Changed on another device');
    await page.getByRole('button',{name:'Close saved work',exact:true}).click();
    await open('t0');
    assert.equal(await page.getByLabel('Project description',{exact:true}).inputValue(),'My unsaved local description');
    await page.getByRole('button',{name:'Discard draft',exact:true}).click();
    assert.equal(await page.getByLabel('Project title',{exact:true}).inputValue(),'Changed on another device');
    await page.getByLabel('Project description',{exact:true}).fill('Safe edit alongside lane move');
    await page.evaluate(()=>window.remoteEditTask('t0',{status:'Today'}));
    await page.getByRole('button',{name:'Save project',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.v2-task-save-actions .v2-primary')?.disabled);
    await page.getByRole('button',{name:/Close saved work/}).click();
    await page.getByRole('region',{name:/Task workspace/}).waitFor({state:'detached'});
    assert.equal(await page.evaluate(()=>window.taskRecords()[0].status),'Today');

    // Append reads the latest task, preserves unknown fields and retries idempotently.
    await paste();
    await page.getByLabel('Import destination',{exact:true}).selectOption('t0');
    await page.getByLabel('Plan text',{exact:true}).fill('1. Appended stage\n   - [ ] Appended substep');
    await page.getByRole('button',{name:'Preview plan',exact:true}).click();
    await page.evaluate(()=>window.deletedTaskId='t0');
    const beforeMissing=await page.evaluate(()=>window.writes);
    await page.getByRole('button',{name:'Add steps to project',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'no longer exists'}).waitFor();
    assert.equal(await page.evaluate(()=>window.writes),beforeMissing,'append cannot recreate a deleted target');
    await page.evaluate(()=>window.deletedTaskId=null);
    await page.evaluate(()=>{
      const task=window.taskRecords()[0];task.steps[0].notes='Latest remote notes';
      window.remoteEditTask('t0',{steps:task.steps});window.loseNextAck=true;
    });
    await page.getByRole('button',{name:'Add steps to project',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'could not be confirmed'}).waitFor();
    assert.equal(await page.evaluate(()=>window.taskRecords()[0].steps.length),3);
    await page.getByLabel('Step 1 title',{exact:true}).fill('Changed after the unconfirmed append');
    await page.getByRole('button',{name:'Add steps to project',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'content differs from this preview'}).waitFor();
    assert.equal(await page.evaluate(()=>window.taskRecords()[0].steps[2].title),'Appended stage','retry cannot silently replace already imported content');
    await page.getByLabel('Step 1 title',{exact:true}).fill('Appended stage');
    await page.getByRole('button',{name:'Add steps to project',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'detached'});
    record=await page.evaluate(()=>window.taskRecords()[0]);
    assert.equal(record.steps.length,3,'retry after a committed but unconfirmed append does not duplicate steps');
    assert.equal(record.title,'Changed on another device');
    assert.equal(record.description,'Safe edit alongside lane move');
    assert.equal(record.steps[0].notes,'Latest remote notes');
    assert.equal(record.steps[0].extension.keep,'nested');
    assert.equal(record.subtasks[0].legacyNotes,'Keep legacy extension');
    assert.equal(record.stepSubsteps[record.steps[2].id][0].title,'Appended substep');

    // A manual project draft is recovered after closing and refreshing.
    await page.getByRole('button',{name:'+ New project',exact:true}).click();
    await page.getByLabel('Project title',{exact:true}).fill('Manual V2 project');
    await page.getByRole('button',{name:'+ Add step',exact:true}).click();
    await page.getByLabel('Step 1 title',{exact:true}).fill('Plan the work');
    await page.getByRole('button',{name:'+ Add substep to step 1',exact:true}).click();
    await page.getByLabel('Substep 1.1 title',{exact:true}).fill('Gather requirements');
    await page.getByRole('button',{name:'Close saved work',exact:true}).click();
    await page.reload();
    await page.getByRole('button',{name:'+ New project',exact:true}).click();
    assert.equal(await page.getByLabel('Project title',{exact:true}).inputValue(),'Manual V2 project');
    assert.equal(await page.getByLabel('Substep 1.1 title',{exact:true}).inputValue(),'Gather requirements');
    await page.getByRole('button',{name:'Save project',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'detached'});
    assert.equal(await page.locator('.v2-task-wrap').filter({hasText:'Manual V2 project'}).count(),1);

    await paste();
    await page.getByLabel('Plan text',{exact:true}).fill('x'.repeat(100001));
    await page.getByRole('button',{name:'Preview plan',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'too long'}).waitFor();
    assert.equal((await page.getByLabel('Plan text',{exact:true}).inputValue()).length,100001,'oversized paste is reported rather than silently truncated');
    await page.getByLabel('Plan text',{exact:true}).fill('- Orphaned substep\n1. Valid main step');
    await page.getByRole('button',{name:'Preview plan',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Check the plan format'}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Create project',exact:true}).isEnabled(),false);
    await page.getByLabel('Plan text',{exact:true}).fill(plan);
    await page.getByRole('button',{name:'Preview plan',exact:true}).click();
    await page.setViewportSize({width:393,height:852});
    assert.equal(await page.locator('.v2-editor').evaluate(element=>element.scrollWidth<=element.clientWidth+1),true);
    await page.screenshot({path:path.join(output,name+'-plan-phone.png')});
    await page.getByRole('button',{name:'Close plan importer',exact:true}).click();
    await page.evaluate(()=>window.switchAccount('bob'));
    await page.getByRole('link',{name:'02 My Workspace'}).click();
    await paste();
    assert.equal(await page.getByLabel('Plan text',{exact:true}).inputValue(),'','another account cannot inherit the saved plan draft');
    await page.getByRole('button',{name:'Close plan importer',exact:true}).click();
    await page.evaluate(()=>window.switchAccount('alice'));
    await page.getByRole('link',{name:'02 My Workspace'}).click();
    await paste();
    assert.equal(await page.getByLabel('Plan text',{exact:true}).inputValue(),plan);
    await page.getByRole('button',{name:'Clear draft',exact:true}).click();
    await page.getByRole('button',{name:'Close plan importer',exact:true}).click();
    assert.deepEqual(errors,[]);
    console.log(name+': plan preview/create/append, nested edits, durable account drafts, denied saves, conflict recovery and idempotent retry passed');
  } finally {await context.close();}
};
